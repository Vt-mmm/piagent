import assert from 'node:assert/strict';
import test from 'node:test';
import { slimPatch, slimSection, DATA_LINES } from '../packages/piagent-core/managed/review-slim.mjs';
import { reviewParts } from '../packages/piagent-core/managed/patch-snapshot.mjs';
import { helperTokens } from '../packages/piagent-core/managed/helper-run.mjs';

// Owner, 2026-11-15: a usage guide with 176 screenshots was reviewed in 72
// parts and 25M tokens; images, generated and large data files are named,
// not read, and the receipt says what the tokens were.
const binary = name => `diff --git a/${name} b/${name}\nnew file mode 100644\nindex 0000000..1111111\nGIT binary patch\nliteral 90000\n${'zcmV+abcdefghij\n'.repeat(6000)}\nliteral 0\nHcmV?d00001\n\n`;
const text = (name, lines) => `diff --git a/${name} b/${name}\nnew file mode 100644\n--- /dev/null\n+++ b/${name}\n@@ -0,0 +1,${lines} @@\n${Array.from({ length: lines }, (_, i) => `+line ${i}`).join('\n')}\n`;

test('a binary, a generated and a large data file are one line each; code is read in full', () => {
  assert.match(slimSection('src/a.webp', binary('src/a.webp')), /^=== binary file src\/a\.webp added: listed, not read\. Check it through the code that uses it/);
  assert.match(slimSection('package-lock.json', text('package-lock.json', 30)), /generated file, 30 lines changed/);
  assert.match(slimSection('web/dist/app.js', text('web/dist/app.js', 3)), /generated file/);
  assert.match(slimSection('src/shots.json', text('src/shots.json', DATA_LINES + 1)), /data file, 1501 lines changed/);
  assert.equal(slimSection('src/small.json', text('src/small.json', 40)), text('src/small.json', 40));
  assert.equal(slimSection('src/usage.tsx', text('src/usage.tsx', 3000)), text('src/usage.tsx', 3000), 'code is never slimmed');
  assert.match(slimSection('src/new.ts', '=== new file src/new.ts\n// @generated by protoc\nx\n', 'new'), /generated file/);
  const patch = slimPatch(binary('a.png') + text('b.ts', 2));
  assert.ok(patch.length < 1000); assert.match(patch, /\+line 1/);
});

test('a guide with many screenshots fits in a few parts', () => {
  const patch = Array.from({ length: 176 }, (_, i) => binary(`guide/s-${i}.webp`)).join('') + text('src/guide.tsx', 400) + text('src/shots.json', 4278);
  const parts = reviewParts({ digest: 'd', patch: JSON.stringify({ patch, untracked: [] }) }).parts;
  assert.equal(parts.length, 1, `${parts.length} parts`);
  assert.match(parts[0].text, /\+line 399/); assert.match(parts[0].text, /src\/shots\.json: data file, 4278 lines changed/);
});

test('the receipt splits the tokens into new reading, cache read again and output', () => {
  assert.equal(helperTokens({ input: 900000, cacheWrite: 300000, cacheRead: 23700000, output: 420000 }), ' (mới 1.2M · đọc lại cache 23.7M · output 420k)');
  assert.equal(helperTokens({ input: 0, cacheWrite: 0, cacheRead: 0, output: 0 }), '');
  assert.equal(helperTokens(undefined), '');
});
