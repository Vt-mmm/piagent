var PRODUCT_INDEX = null;
function productBySku(sku) {
  if (PRODUCT_INDEX === null) {
    PRODUCT_INDEX = {};
    for (var i = 0; i < PRODUCTS.length; i++) PRODUCT_INDEX[PRODUCTS[i].sku] = PRODUCTS[i];
  }
  return hasOwn(PRODUCT_INDEX, sku) ? PRODUCT_INDEX[sku] : null;
}

function provinceByCode(code) {
  for (var i = 0; i < PROVINCES.length; i++) {
    if (PROVINCES[i].code === code) return PROVINCES[i];
  }
  return null;
}

function promoByCode(code) {
  var wanted = String(code).toUpperCase();
  for (var i = 0; i < PROMOS.length; i++) {
    if (PROMOS[i].code === wanted) return PROMOS[i];
  }
  return null;
}

function categoryExists(name) {
  for (var i = 0; i < CATEGORIES.length; i++) {
    if (CATEGORIES[i].id === name) return true;
  }
  return false;
}

function taxRate(category) {
  return hasOwn(TAX_RATES, category) ? TAX_RATES[category] : 10;
}

function readCurrency(value) {
  if (value === undefined || value === null || value === '') return 'VND';
  var c = String(value).toUpperCase();
  if (c !== 'VND' && c !== 'USD') fail(400, 'bad_currency', value);
  return c;
}

