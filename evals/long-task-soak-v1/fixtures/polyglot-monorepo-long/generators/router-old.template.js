function productView(p, lang, currency) {
  var price = vndToCurrency(p.price, currency);
  return {
    sku: p.sku,
    name: lang === 'en' && p.name_en ? p.name_en : p.name,
    slug: slugify(p.name),
    category: p.category,
    price: price,
    price_display: formatMoney(price, currency),
    currency: currency,
    in_stock: p.active && p.stock > 0,
    tags: p.tags.slice(0)
  };
}

function productDetailView(p, lang, currency) {
  var view = productView(p, lang, currency);
  var rate = taxRate(p.category);
  var taxVnd = Math.round((p.price * rate) / 100);
  view.stock = p.stock;
  view.active = p.active;
  view.weight_grams = p.weight;
  view.tax_rate = rate;
  view.tax = vndToCurrency(taxVnd, currency);
  view.price_with_tax = vndToCurrency(p.price + taxVnd, currency);
  view.price_with_tax_display = formatMoney(view.price_with_tax, currency);
  return view;
}

