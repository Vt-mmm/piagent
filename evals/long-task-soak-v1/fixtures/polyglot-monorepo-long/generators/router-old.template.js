function dispatch(name, params, query, body, lang) {
  switch (name) {
    case 'health':
      return handleHealth();
    case 'catalog':
      return handleCatalog(query, lang);
    case 'categories':
      return handleCategories(lang);
    case 'product_related':
      return handleRelated(params[0], query, lang);
    case 'product':
      return handleProduct(params[0].toUpperCase(), query, lang);
    case 'cart_preview':
      return handleCartPreview(body, lang);
    case 'shipping_quote':
      return handleShippingQuote(query, lang);
    case 'provinces':
      return handleProvinces(query, lang);
    case 'promo_validate':
      return handlePromoValidate(body, lang);
    case 'suggest':
      return handleSuggest(query, lang);
    case 'account_note':
      return handleAccountNote(safeDecode(params[0]), body, lang);
    case 'sales_report':
      return handleSalesReport(query, lang);
    case 'top_products':
      return handleTopProducts(query, lang);
    case 'stock_alerts':
      return handleStockAlerts(query, lang);
    case 'calendar':
      return handleCalendar(query, lang);
  }
  return null;
}

function readBody(raw) {
  if (raw === undefined || raw === null) return undefined;
  if (typeof raw === 'string') {
    if (raw.length === 0) return undefined;
    try {
      return JSON.parse(raw);
    } catch (e) {
      return null;
    }
  }
  return clone(raw);
}

/**
 * The one entry point.
 * @param {{method?: string, url?: string, headers?: object, body?: any}} request
 */
function route(request) {
  request = request || {};
  var method = String(request.method || 'GET').toUpperCase();
  var parsed = parseUrl(request.url);
  var lang = pickLang(request.headers);
  var allowed = [];
  for (var i = 0; i < ROUTES.length; i++) {
    var r = ROUTES[i];
    var m = r.pattern.exec(parsed.pathname);
    if (!m) continue;
    if (r.methods.indexOf(method) < 0) {
      allowed = allowed.concat(r.methods);
      continue;
    }
    try {
      var response = dispatch(r.name, m.slice(1), parsed.query, readBody(request.body), lang);
      response.headers['x-legacy-route'] = r.name;
      if (method === 'HEAD') response.body = null;
      return response;
    } catch (e) {
      if (e instanceof LegacyError) {
        var errorResponse = respond(e.status, e.toBody(lang));
        errorResponse.headers['x-legacy-route'] = r.name;
        return errorResponse;
      }
      throw e;
    }
  }
  if (allowed.length > 0) {
    return respond(405, new LegacyError(405, 'method_not_allowed', [method, parsed.pathname]).toBody(lang), { allow: allowed.join(', ') });
  }
  return respond(404, new LegacyError(404, 'not_found', [parsed.pathname]).toBody(lang));
}

