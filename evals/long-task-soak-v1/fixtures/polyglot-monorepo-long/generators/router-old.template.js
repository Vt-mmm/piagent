/**
 * Error carrying an HTTP status and a message key.
 * @constructor
 */
function LegacyError(status, key, args) {
  this.status = status;
  this.key = key;
  this.args = args || [];
}
LegacyError.prototype.toBody = function (lang) {
  return { error: { code: this.key.toUpperCase(), message: msg(lang, this.key, this.args) } };
};

function msg(lang, key, args) {
  var table = MESSAGES[lang] || MESSAGES.vi;
  var text = table[key] || key;
  args = args || [];
  for (var i = 0; i < args.length; i++) {
    text = text.split('{' + i + '}').join(String(args[i]));
  }
  return text;
}

function pickLang(headers) {
  if (!headers) return 'vi';
  var value = headers['accept-language'] || headers['Accept-Language'] || '';
  value = String(value).toLowerCase();
  if (value.indexOf('en') === 0) return 'en';
  return 'vi';
}

function hasOwn(obj, key) {
  return Object.prototype.hasOwnProperty.call(obj, key);
}

function safeDecode(text) {
  try {
    return decodeURIComponent(text);
  } catch (e) {
    return text;
  }
}

/**
 * "/v1/catalog?page=2&q=tra+xanh" -> { pathname: '/v1/catalog', query: { page: '2', q: 'tra xanh' } }
 * Repeated keys: the last one wins. A key without "=" is "".
 */
function parseUrl(url) {
  var text = String(url || '/');
  var hashAt = text.indexOf('#');
  if (hashAt >= 0) text = text.substring(0, hashAt);
  var qAt = text.indexOf('?');
  var pathname = qAt >= 0 ? text.substring(0, qAt) : text;
  var search = qAt >= 0 ? text.substring(qAt + 1) : '';
  var query = {};
  if (search.length > 0) {
    var pairs = search.split('&');
    for (var i = 0; i < pairs.length; i++) {
      if (pairs[i] === '') continue;
      var eq = pairs[i].indexOf('=');
      var key, value;
      if (eq < 0) {
        key = pairs[i];
        value = '';
      } else {
        key = pairs[i].substring(0, eq);
        value = pairs[i].substring(eq + 1);
      }
      key = safeDecode(key.replace(/\+/g, ' '));
      value = safeDecode(value.replace(/\+/g, ' '));
      query[key] = value;
    }
  }
  if (pathname.length > 1 && pathname.charAt(pathname.length - 1) === '/') {
    pathname = pathname.substring(0, pathname.length - 1);
  }
  return { pathname: pathname, query: query };
}

function toInt(value, fallback) {
  if (value === undefined || value === null || value === '') return fallback;
  var n = parseInt(value, 10);
  if (isNaN(n)) return fallback;
  return n;
}

function clamp(n, lo, hi) {
  if (n < lo) return lo;
  if (n > hi) return hi;
  return n;
}

function padLeft(text, width, fill) {
  text = String(text);
  fill = fill || ' ';
  while (text.length < width) text = fill + text;
  return text;
}

function groupDigits(digits, sep) {
  var out = '';
  var count = 0;
  for (var i = digits.length - 1; i >= 0; i--) {
    out = digits.charAt(i) + out;
    count++;
    if (count % 3 === 0 && i > 0) out = sep + out;
  }
  return out;
}

/**
 * VND: 1.234.000 ₫   USD (amount in cents): $1,234.50
 */
function formatMoney(amount, currency) {
  var negative = amount < 0;
  var abs = Math.abs(amount);
  var text;
  if (currency === 'USD') {
    var dollars = Math.floor(abs / 100);
    var cents = abs % 100;
    text = '$' + groupDigits(String(dollars), ',') + '.' + padLeft(cents, 2, '0');
  } else {
    text = groupDigits(String(abs), '.') + ' ₫';
  }
  return negative ? '-' + text : text;
}

function vndToCurrency(amountVnd, currency) {
  if (currency === 'USD') {
    // cents, rounded half up
    return Math.floor((amountVnd * 100) / USD_RATE_VND + 0.5);
  }
  return amountVnd;
}

function removeDiacritics(text) {
  var out = '';
  for (var i = 0; i < text.length; i++) {
    var ch = text.charAt(i);
    out += hasOwn(DIACRITICS, ch) ? DIACRITICS[ch] : ch;
  }
  return out;
}

function slugify(text) {
  var plain = removeDiacritics(String(text)).toLowerCase();
  var out = '';
  var dash = false;
  for (var i = 0; i < plain.length; i++) {
    var ch = plain.charAt(i);
    if ((ch >= 'a' && ch <= 'z') || (ch >= '0' && ch <= '9')) {
      out += ch;
      dash = false;
    } else if (!dash && out.length > 0) {
      out += '-';
      dash = true;
    }
  }
  if (out.charAt(out.length - 1) === '-') out = out.substring(0, out.length - 1);
  return out;
}

function clone(value) {
  return JSON.parse(JSON.stringify(value));
}

function compareBy(field, direction) {
  var sign = direction === 'desc' ? -1 : 1;
  return function (a, b) {
    var x = a[field];
    var y = b[field];
    if (x < y) return -1 * sign;
    if (x > y) return 1 * sign;
    // stable tie-break on sku so pages never shuffle
    if (a.sku < b.sku) return -1;
    if (a.sku > b.sku) return 1;
    return 0;
  };
}

function paginate(list, page, perPage) {
  var total = list.length;
  var pages = total === 0 ? 0 : Math.ceil(total / perPage);
  var start = (page - 1) * perPage;
  return {
    items: list.slice(start, start + perPage),
    page: page,
    per_page: perPage,
    total: total,
    pages: pages
  };
}

function csvEscape(value) {
  var text = value === null || value === undefined ? '' : String(value);
  if (text.indexOf(';') >= 0 || text.indexOf('"') >= 0 || text.indexOf('\n') >= 0) {
    return '"' + text.replace(/"/g, '""') + '"';
  }
  return text;
}

var DATE_RE = /^(\d{4})-(\d{2})-(\d{2})$/;

/** YYYY-MM-DD with month 01-12 and day 01-31 (month length is not checked). */
function isDate(text) {
  var m = DATE_RE.exec(String(text));
  if (!m) return false;
  var month = parseInt(m[2], 10);
  var day = parseInt(m[3], 10);
  return month >= 1 && month <= 12 && day >= 1 && day <= 31;
}

function dayNumber(text) {
  var m = DATE_RE.exec(text);
  return Math.floor(Date.UTC(parseInt(m[1], 10), parseInt(m[2], 10) - 1, parseInt(m[3], 10)) / 86400000);
}

function dateFromDayNumber(n) {
  var d = new Date(n * 86400000);
  return d.getUTCFullYear() + '-' + padLeft(d.getUTCMonth() + 1, 2, '0') + '-' + padLeft(d.getUTCDate(), 2, '0');
}

/** ISO week key, e.g. 2025-W07. */
function isoWeek(text) {
  var n = dayNumber(text);
  var d = new Date(n * 86400000);
  var weekday = (d.getUTCDay() + 6) % 7; // Monday = 0
  var thursday = n - weekday + 3;
  var t = new Date(thursday * 86400000);
  var year = t.getUTCFullYear();
  var jan1 = Math.floor(Date.UTC(year, 0, 1) / 86400000);
  var week = Math.floor((thursday - jan1) / 7) + 1;
  return year + '-W' + padLeft(week, 2, '0');
}

function respond(status, body, extraHeaders) {
  var headers = { 'content-type': 'application/json; charset=utf-8', 'x-legacy-version': LEGACY_VERSION };
  if (extraHeaders) {
    for (var key in extraHeaders) {
      if (hasOwn(extraHeaders, key)) headers[key] = extraHeaders[key];
    }
  }
  return { status: status, headers: headers, body: body };
}

function respondText(status, text, contentType) {
  return {
    status: status,
    headers: { 'content-type': contentType, 'x-legacy-version': LEGACY_VERSION },
    body: text
  };
}

function fail(status, key) {
  var args = Array.prototype.slice.call(arguments, 2);
  throw new LegacyError(status, key, args);
}

