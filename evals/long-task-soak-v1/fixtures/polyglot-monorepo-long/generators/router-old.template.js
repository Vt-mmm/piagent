function handleCatalog(query, lang) {
  var page = toInt(query.page, 1);
  if (page < 1) fail(400, 'bad_page');
  var perPage = toInt(query.per_page, DEFAULT_PER_PAGE);
  if (!perPage) perPage = DEFAULT_PER_PAGE;
  perPage = clamp(perPage, 1, MAX_PER_PAGE);
  var currency = readCurrency(query.currency);
  var category = query.category;
  if (category && !categoryExists(category)) fail(400, 'bad_category', category);
  var sort = query.sort || 'sku';
  var sortField, sortDir;
  if (sort === 'sku') { sortField = 'sku'; sortDir = 'asc'; }
  else if (sort === 'name') { sortField = 'name'; sortDir = 'asc'; }
  else if (sort === 'price') { sortField = 'price'; sortDir = 'asc'; }
  else if (sort === '-price') { sortField = 'price'; sortDir = 'desc'; }
  else if (sort === 'stock') { sortField = 'stock'; sortDir = 'desc'; }
  else fail(400, 'bad_sort', sort);
  var needle = query.q ? slugify(query.q) : '';
  var includeInactive = query.include_inactive === '1' || query.include_inactive === 'true';
  var list = [];
  for (var i = 0; i < PRODUCTS.length; i++) {
    var p = PRODUCTS[i];
    if (!includeInactive && !p.active) continue;
    if (category && p.category !== category) continue;
    if (needle && slugify(p.name).indexOf(needle) < 0 && p.sku.toLowerCase().indexOf(needle) < 0) continue;
    if (query.tag && p.tags.indexOf(query.tag) < 0) continue;
    list.push(p);
  }
  list.sort(compareBy(sortField, sortDir));
  var result = paginate(list, page, perPage);
  var items = [];
  for (var j = 0; j < result.items.length; j++) items.push(productView(result.items[j], lang, currency));
  result.items = items;
  result.sort = sort;
  return respond(200, result);
}

function handleProduct(sku, query, lang) {
  var p = productBySku(sku);
  if (!p) fail(404, 'product_not_found', sku);
  var currency = readCurrency(query.currency);
  return respond(200, productDetailView(p, lang, currency));
}

function handleRelated(sku, query, lang) {
  var p = productBySku(sku);
  if (!p) fail(404, 'product_not_found', sku);
  var currency = readCurrency(query.currency);
  var limit = clamp(toInt(query.limit, 5), 1, 20);
  var scored = [];
  for (var i = 0; i < PRODUCTS.length; i++) {
    var other = PRODUCTS[i];
    if (other.sku === p.sku || !other.active) continue;
    var shared = 0;
    for (var t = 0; t < other.tags.length; t++) {
      if (p.tags.indexOf(other.tags[t]) >= 0) shared++;
    }
    if (other.category === p.category) shared += 0.5;
    if (shared > 0) scored.push({ score: shared, product: other });
  }
  scored.sort(function (a, b) {
    if (b.score !== a.score) return b.score - a.score;
    return a.product.sku < b.product.sku ? -1 : 1;
  });
  var items = [];
  for (var k = 0; k < scored.length && k < limit; k++) {
    var view = productView(scored[k].product, lang, currency);
    view.score = scored[k].score;
    items.push(view);
  }
  return respond(200, { sku: p.sku, items: items });
}

function handleCategories(lang) {
  var counts = {};
  var i;
  for (i = 0; i < PRODUCTS.length; i++) {
    var p = PRODUCTS[i];
    if (!counts[p.category]) counts[p.category] = { active: 0, inactive: 0, stock: 0 };
    if (p.active) counts[p.category].active++;
    else counts[p.category].inactive++;
    counts[p.category].stock += p.stock;
  }
  var out = [];
  for (i = 0; i < CATEGORIES.length; i++) {
    var c = CATEGORIES[i];
    var n = counts[c.id] || { active: 0, inactive: 0, stock: 0 };
    out.push({
      id: c.id,
      name: lang === 'en' ? c.name_en : c.name,
      tax_rate: taxRate(c.id),
      active: n.active,
      inactive: n.inactive,
      stock: n.stock
    });
  }
  return respond(200, { categories: out });
}

function shippingFor(provinceCode, weightGrams, subtotalVnd) {
  var province = provinceByCode(provinceCode);
  if (!province) fail(400, 'bad_province', provinceCode);
  var zone = ZONES[province.zone];
  var weight = weightGrams;
  if (!weight) weight = WEIGHT_STEP_GRAMS; // quirk: 0 is billed as 500 g
  var steps = Math.ceil(weight / WEIGHT_STEP_GRAMS);
  var fee = zone.base + (steps - 1) * zone.step;
  if (province.remote) fee += REMOTE_SURCHARGE_VND;
  var free = subtotalVnd !== null && subtotalVnd >= FREE_SHIPPING_THRESHOLD_VND && !province.remote;
  return {
    province: province.code,
    province_name: province.name,
    zone: province.zone,
    remote: province.remote,
    weight_grams: weight,
    fee: free ? 0 : fee,
    days: zone.days + (province.remote ? 2 : 0),
    free_shipping: free
  };
}

function handleShippingQuote(query, lang) {
  var code = query.province;
  if (!code) fail(400, 'bad_province', '');
  var weight = 0;
  if (query.weight !== undefined && query.weight !== '') {
    weight = Number(query.weight);
    if (isNaN(weight) || weight < 0 || weight > 30000) fail(400, 'bad_weight', query.weight);
  }
  var currency = readCurrency(query.currency);
  var quote = shippingFor(String(code).toUpperCase(), weight, null);
  quote.fee = vndToCurrency(quote.fee, currency);
  quote.fee_display = formatMoney(quote.fee, currency);
  quote.currency = currency;
  return respond(200, quote);
}

function handleProvinces(query, lang) {
  var zone = query.zone ? String(query.zone).toUpperCase() : '';
  var out = [];
  for (var i = 0; i < PROVINCES.length; i++) {
    var p = PROVINCES[i];
    if (zone && p.zone !== zone) continue;
    if (query.remote === '1' && !p.remote) continue;
    out.push({ code: p.code, name: p.name, slug: slugify(p.name), zone: p.zone, remote: p.remote });
  }
  if (query.sort === 'name') {
    out.sort(function (a, b) { return a.slug < b.slug ? -1 : a.slug > b.slug ? 1 : 0; });
  }
  return respond(200, { total: out.length, provinces: out });
}

/**
 * Applies a promo to a subtotal (VND). categories: categories present in the cart.
 * Returns { code, kind, discount, free_shipping } or throws.
 */
function applyPromo(rawCode, subtotalVnd, categories) {
  var promo = promoByCode(rawCode);
  if (!promo) fail(422, 'promo_unknown');
  if (promo.expired) fail(422, 'promo_expired');
  if (subtotalVnd < promo.min_subtotal) fail(422, 'promo_min', formatMoney(promo.min_subtotal, 'VND'));
  if (promo.category && categories.indexOf(promo.category) < 0) fail(422, 'promo_category', promo.category);
  var discount = 0;
  var freeShipping = false;
  if (promo.kind === 'percent') {
    discount = Math.floor((subtotalVnd * promo.value) / 100);
    if (promo.max_discount && discount > promo.max_discount) discount = promo.max_discount;
  } else if (promo.kind === 'fixed') {
    discount = promo.value;
    if (discount > subtotalVnd) discount = subtotalVnd;
  } else if (promo.kind === 'freeship') {
    freeShipping = true;
  }
  return { code: promo.code, kind: promo.kind, discount: discount, free_shipping: freeShipping };
}

function handlePromoValidate(body, lang) {
  if (!body || typeof body !== 'object' || Array.isArray(body)) fail(400, 'bad_body');
  var subtotal = Number(body.subtotal);
  if (isNaN(subtotal) || subtotal < 0) subtotal = 0;
  var categories = [];
  if (body.category) categories.push(String(body.category));
  if (Array.isArray(body.categories)) {
    for (var i = 0; i < body.categories.length; i++) categories.push(String(body.categories[i]));
  }
  var result = applyPromo(body.code === undefined ? '' : body.code, subtotal, categories);
  result.valid = true;
  result.discount_display = formatMoney(result.discount, 'VND');
  return respond(200, result);
}

function handleCartPreview(body, lang) {
  if (!body || typeof body !== 'object' || Array.isArray(body)) fail(400, 'bad_body');
  var lines = body.items;
  if (!Array.isArray(lines) || lines.length === 0) fail(400, 'empty_cart');
  if (lines.length > MAX_CART_LINES) fail(400, 'too_many_lines', MAX_CART_LINES);
  var currency = readCurrency(body.currency);
  var merged = {};
  var order = [];
  var i;
  for (i = 0; i < lines.length; i++) {
    var line = lines[i] || {};
    var qty = line.qty;
    if (typeof qty === 'string') qty = parseInt(qty, 10);
    if (qty == 0 || typeof qty !== 'number' || isNaN(qty) || qty < 0 || Math.floor(qty) !== qty || qty > MAX_QTY_PER_LINE) {
      fail(400, 'bad_qty', i + 1);
    }
    var p = productBySku(line.sku);
    if (!p) fail(404, 'product_not_found', line.sku);
    if (!p.active) fail(409, 'inactive_product', p.sku);
    if (!hasOwn(merged, p.sku)) {
      merged[p.sku] = 0;
      order.push(p.sku);
    }
    merged[p.sku] += qty;
  }
  var outLines = [];
  var subtotal = 0;
  var tax = 0;
  var weight = 0;
  var categories = [];
  for (i = 0; i < order.length; i++) {
    var product = productBySku(order[i]);
    var count = merged[order[i]];
    if (count > product.stock) fail(409, 'out_of_stock', product.sku, product.stock);
    var lineTotal = product.price * count;
    var lineTax = Math.round((lineTotal * taxRate(product.category)) / 100);
    subtotal += lineTotal;
    tax += lineTax;
    weight += product.weight * count;
    if (categories.indexOf(product.category) < 0) categories.push(product.category);
    outLines.push({
      sku: product.sku,
      name: lang === 'en' && product.name_en ? product.name_en : product.name,
      qty: count,
      unit_price: vndToCurrency(product.price, currency),
      line_total: vndToCurrency(lineTotal, currency),
      tax: vndToCurrency(lineTax, currency)
    });
  }
  var promo = null;
  var discount = 0;
  var promoError = null;
  if (body.promo !== undefined && body.promo !== null && body.promo !== '') {
    try {
      promo = applyPromo(body.promo, subtotal, categories);
      discount = promo.discount;
    } catch (e) {
      if (!(e instanceof LegacyError)) throw e;
      promoError = { code: e.key.toUpperCase(), message: msg(lang, e.key, e.args) };
    }
  }
  var shipping = null;
  if (body.province) {
    shipping = shippingFor(String(body.province).toUpperCase(), weight, subtotal - discount);
    if (promo && promo.free_shipping && !shipping.remote) {
      shipping.fee = 0;
      shipping.free_shipping = true;
    }
  }
  var shippingFee = shipping ? shipping.fee : 0;
  var total = subtotal - discount + tax + shippingFee;
  var result = {
    currency: currency,
    lines: outLines,
    weight_grams: weight,
    subtotal: vndToCurrency(subtotal, currency),
    discount: vndToCurrency(discount, currency),
    tax: vndToCurrency(tax, currency),
    shipping: shipping ? vndToCurrency(shippingFee, currency) : null,
    total: vndToCurrency(total, currency),
    total_display: formatMoney(vndToCurrency(total, currency), currency),
    promo: promo ? promo.code : null
  };
  if (promoError) result.promo_error = promoError;
  if (shipping) {
    result.delivery_days = shipping.days;
    result.zone = shipping.zone;
  }
  if (currency === 'USD' && vndToCurrency(subtotal, currency) >= FREE_SHIPPING_THRESHOLD_USD * 100) {
    result.note = 'large_order';
  }
  return respond(200, result);
}

function handleSuggest(query, lang) {
  var q = query.q ? slugify(query.q) : '';
  if (q.length < 2) fail(400, 'query_too_short');
  var limit = clamp(toInt(query.limit, 8), 1, 20);
  var prefix = [];
  var inner = [];
  for (var i = 0; i < PRODUCTS.length; i++) {
    var p = PRODUCTS[i];
    if (!p.active) continue;
    var slug = slugify(p.name);
    var at = slug.indexOf(q);
    if (at === 0) prefix.push({ sku: p.sku, name: p.name, slug: slug });
    else if (at > 0) inner.push({ sku: p.sku, name: p.name, slug: slug });
  }
  var bySlug = function (a, b) { return a.slug < b.slug ? -1 : a.slug > b.slug ? 1 : 0; };
  prefix.sort(bySlug);
  inner.sort(bySlug);
  var all = prefix.concat(inner).slice(0, limit);
  return respond(200, { q: q, suggestions: all });
}

var ACCOUNT_ID_RE = /^A-\d{3,6}$/;

function handleAccountNote(accountId, body, lang) {
  if (!ACCOUNT_ID_RE.test(accountId)) fail(400, 'bad_account', accountId);
  if (!body || typeof body !== 'object' || Array.isArray(body)) fail(400, 'bad_body');
  var text = typeof body.text === 'string' ? body.text.replace(/^\s+|\s+$/g, '') : '';
  if (text.length === 0) fail(400, 'note_required');
  if (text.length > MAX_NOTE_LENGTH) fail(400, 'note_too_long', MAX_NOTE_LENGTH);
  var tags = [];
  if (body.tags !== undefined) {
    if (!Array.isArray(body.tags)) fail(400, 'bad_tags');
    for (var i = 0; i < body.tags.length; i++) {
      if (typeof body.tags[i] !== 'string') fail(400, 'bad_tags');
      var tag = body.tags[i].toLowerCase().replace(/^\s+|\s+$/g, '');
      if (tag && tags.indexOf(tag) < 0) tags.push(tag);
    }
  }
  tags.sort();
  var words = text.split(/\s+/).length;
  var pinned = body.pinned === true || body.pinned === 'true';
  return respond(201, {
    account_id: accountId,
    text: text,
    tags: tags,
    words: words,
    pinned: pinned,
    preview: text.length > 40 ? text.substring(0, 37) + '...' : text
  }, { location: '/v1/accounts/' + accountId + '/notes/draft' });
}

function readRange(query) {
  var from = query.from || '2025-01-01';
  var to = query.to || '2025-12-31';
  if (!isDate(from)) fail(400, 'bad_date', from);
  if (!isDate(to)) fail(400, 'bad_date', to);
  if (from > to) fail(400, 'bad_range');
  return { from: from, to: to };
}

function salesKey(row, group) {
  if (group === 'day') return row.date;
  if (group === 'week') return isoWeek(row.date);
  if (group === 'month') return row.date.substring(0, 7);
  if (group === 'category') return productBySku(row.sku).category;
  if (group === 'province') return row.province;
  if (group === 'zone') return provinceByCode(row.province).zone;
  return null;
}

function handleSalesReport(query, lang) {
  var range = readRange(query);
  var group = query.group || 'month';
  if (['day', 'week', 'month', 'category', 'province', 'zone'].indexOf(group) < 0) fail(400, 'bad_group', group);
  var format = query.format || 'json';
  if (format !== 'json' && format !== 'csv') fail(400, 'bad_format', format);
  var buckets = {};
  var keys = [];
  var totalQty = 0;
  var totalRevenue = 0;
  for (var i = 0; i < SALES.length; i++) {
    var row = SALES[i];
    if (row.date < range.from || row.date > range.to) continue;
    if (query.category && productBySku(row.sku).category !== query.category) continue;
    var key = salesKey(row, group);
    if (!hasOwn(buckets, key)) {
      buckets[key] = { key: key, orders: 0, qty: 0, revenue: 0 };
      keys.push(key);
    }
    var revenue = row.qty * row.unit_price;
    buckets[key].orders += 1;
    buckets[key].qty += row.qty;
    buckets[key].revenue += revenue;
    totalQty += row.qty;
    totalRevenue += revenue;
  }
  keys.sort();
  var rows = [];
  for (var k = 0; k < keys.length; k++) {
    var b = buckets[keys[k]];
    b.avg_order = b.orders ? Math.round(b.revenue / b.orders) : 0;
    rows.push(b);
  }
  if (format === 'csv') {
    var csv = 'key;orders;qty;revenue;avg_order\n';
    for (var r = 0; r < rows.length; r++) {
      csv += [csvEscape(rows[r].key), rows[r].orders, rows[r].qty, rows[r].revenue, rows[r].avg_order].join(';') + '\n';
    }
    csv += 'TOTAL;' + rows.reduce(function (s, x) { return s + x.orders; }, 0) + ';' + totalQty + ';' + totalRevenue + ';\n';
    return respondText(200, csv, 'text/csv; charset=utf-8');
  }
  return respond(200, {
    from: range.from,
    to: range.to,
    group: group,
    rows: rows,
    total_qty: totalQty,
    total_revenue: totalRevenue,
    total_revenue_display: formatMoney(totalRevenue, 'VND')
  });
}

function handleTopProducts(query, lang) {
  var n = toInt(query.n, 10);
  if (n < 1 || n > 50) fail(400, 'bad_n');
  var by = query.by === 'revenue' ? 'revenue' : 'qty';
  var range = readRange(query);
  var stats = {};
  for (var i = 0; i < SALES.length; i++) {
    var row = SALES[i];
    if (row.date < range.from || row.date > range.to) continue;
    if (!stats[row.sku]) stats[row.sku] = { sku: row.sku, qty: 0, revenue: 0 };
    stats[row.sku].qty += row.qty;
    stats[row.sku].revenue += row.qty * row.unit_price;
  }
  var list = [];
  for (var sku in stats) {
    if (hasOwn(stats, sku)) list.push(stats[sku]);
  }
  list.sort(function (a, b) {
    if (b[by] !== a[by]) return b[by] - a[by];
    return a.sku < b.sku ? -1 : 1;
  });
  list = list.slice(0, n);
  for (var j = 0; j < list.length; j++) {
    var p = productBySku(list[j].sku);
    list[j].rank = j + 1;
    list[j].name = lang === 'en' && p.name_en ? p.name_en : p.name;
    list[j].revenue_display = formatMoney(list[j].revenue, 'VND');
  }
  return respond(200, { by: by, from: range.from, to: range.to, items: list });
}

function handleStockAlerts(query, lang) {
  var threshold = 10;
  if (query.threshold !== undefined) {
    threshold = Number(query.threshold);
    if (isNaN(threshold) || threshold < 0 || Math.floor(threshold) !== threshold) fail(400, 'bad_threshold');
  }
  var out = [];
  for (var i = 0; i < PRODUCTS.length; i++) {
    var p = PRODUCTS[i];
    if (!p.active) continue;
    if (p.stock <= threshold) {
      out.push({
        sku: p.sku,
        name: p.name,
        stock: p.stock,
        level: p.stock === 0 ? 'out' : p.stock <= threshold / 2 ? 'critical' : 'low'
      });
    }
  }
  out.sort(function (a, b) {
    if (a.stock !== b.stock) return a.stock - b.stock;
    return a.sku < b.sku ? -1 : 1;
  });
  return respond(200, { threshold: threshold, count: out.length, items: out });
}

function handleCalendar(query, lang) {
  var from = query.from;
  if (!from || !isDate(from)) fail(400, 'bad_date', from === undefined ? '' : from);
  var days = clamp(toInt(query.days, 7), 1, 31);
  var start = dayNumber(from);
  var out = [];
  for (var i = 0; i < days; i++) {
    var date = dateFromDayNumber(start + i);
    var weekday = new Date((start + i) * 86400000).getUTCDay();
    var orders = 0;
    for (var s = 0; s < SALES.length; s++) {
      if (SALES[s].date === date) orders++;
    }
    out.push({ date: date, week: isoWeek(date), weekend: weekday === 0 || weekday === 6, orders: orders });
  }
  return respond(200, { from: dateFromDayNumber(start), days: out });
}

